"""Put a trained model into the firmware.

Writes `firmware/src/model_data.h` and `model_data.cpp` from a model folder of
the training notebook: the int8 model as a C array plus its label list, so the
two cannot get out of step.

    uv run python -m fairy_kws.firmware                       # models/<wake word>/ds_cnn
    uv run python -m fairy_kws.firmware models/crystal/tiny_conv

Then build and flash with PlatformIO, see firmware/README.md.
"""

import argparse
from pathlib import Path

from fairy_kws import config
from fairy_kws.export import Int8Model, c_array

FIRMWARE_SRC = config.REPO_ROOT / "firmware" / "src"

# The firmware turns the audio front end's output into int8 model input with fixed
# arithmetic (micro_features_micro_features_generator.cpp): one int8 step is
# 25.6 * 26 / 256 front end units, which are 1 / 25.6 of a training feature unit.
FIRMWARE_INPUT_SCALE = 26.0 / 256.0
FIRMWARE_INPUT_ZERO_POINT = -128


def check_input_scaling(tflite_model: bytes) -> None:
    """Fail if the model expects its input scaled differently from what the firmware does."""
    scale, zero_point = Int8Model(tflite_model).input["quantization"]
    if zero_point != FIRMWARE_INPUT_ZERO_POINT or abs(scale / FIRMWARE_INPUT_SCALE - 1) > 0.02:
        raise ValueError(
            f"model input quantisation is (scale {scale:.5f}, zero point {zero_point}), but the "
            f"firmware produces (scale {FIRMWARE_INPUT_SCALE:.5f}, zero point "
            f"{FIRMWARE_INPUT_ZERO_POINT}); the board would feed the model wrong values"
        )


def write_model_sources(model_dir: Path, out_dir: Path = FIRMWARE_SRC) -> list[Path]:
    """Write model_data.h and model_data.cpp for the model in `model_dir`."""
    tflite_model = (model_dir / "model_int8.tflite").read_bytes()
    labels = (model_dir / "labels.txt").read_text().split()
    if labels[:2] != [config.SILENCE_LABEL, config.UNKNOWN_LABEL]:
        raise ValueError(f"labels must start with silence and unknown, got {labels[:2]}")
    check_input_scaling(tflite_model)

    name = f"{model_dir.parent.name}/{model_dir.name}"
    generated = f"// Generated by `uv run python -m fairy_kws.firmware` from models/{name}.\n"
    header = f"""{generated}// Do not edit: run the command again after training a new model.

#ifndef FAIRY_LIGHT_SENSE_MODEL_DATA_H_
#define FAIRY_LIGHT_SENSE_MODEL_DATA_H_

constexpr char kModelName[] = "{name}";

// Output categories of the model, in order. The wake word is the first keyword.
constexpr int kCategoryCount = {len(labels)};
constexpr int kSilenceIndex = 0;
constexpr int kUnknownIndex = 1;
constexpr int kWakeWordIndex = 2;
extern const char* const kCategoryLabels[kCategoryCount];

// The int8 TensorFlow Lite model.
extern const unsigned char g_model[];
extern const int g_model_len;

#endif  // FAIRY_LIGHT_SENSE_MODEL_DATA_H_
"""
    label_rows = "".join(f'    "{label}",\n' for label in labels)
    source = f"""{generated}
#include "model_data.h"

const char* const kCategoryLabels[kCategoryCount] = {{
{label_rows}}};

{c_array(tflite_model)}"""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = [out_dir / "model_data.h", out_dir / "model_data.cpp"]
    paths[0].write_text(header)
    paths[1].write_text(source)
    return paths


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "model",
        nargs="?",
        type=Path,
        default=config.MODELS_DIR / config.WAKE_WORD / "ds_cnn",
        help="model folder written by the training notebook (default: %(default)s)",
    )
    args = parser.parse_args(argv)
    for path in write_model_sources(args.model):
        print(f"wrote {path.relative_to(config.REPO_ROOT)}")


if __name__ == "__main__":
    main()
